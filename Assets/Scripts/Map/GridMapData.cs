using System.Collections.Generic;
using System;
using UnityEngine;

namespace LoadGame.Map
{
    public enum RoadSource
    {
        None,
        AutoGenerated,
        PlayerBuilt
    }

    public sealed class GridMapData
    {
        private readonly Dictionary<Vector2Int, GridCellData> cellsByPosition = new Dictionary<Vector2Int, GridCellData>();
        private readonly HashSet<Vector2Int> authoredCellPositions = new HashSet<Vector2Int>();
        private readonly Dictionary<string, BuildingInstance> buildingInstancesById = new Dictionary<string, BuildingInstance>();
        private readonly HashSet<Vector2Int> developedCells = new HashSet<Vector2Int>();
        private readonly HashSet<Vector2Int> revealedCells = new HashSet<Vector2Int>();
        private readonly HashSet<Vector2Int> clearedDecorationCells = new HashSet<Vector2Int>();
        private readonly HashSet<Vector2Int> removedAutoRoads = new HashSet<Vector2Int>();
        private ProceduralRoadNetwork proceduralRoadNetwork;
        private WorldGenerationSettings worldSettings;
        private int nextBuildingInstanceId = 1;

        public int ChunkSize { get; }
        public RectIntJson CameraBounds { get; }
        public IEnumerable<GridCellData> Cells => cellsByPosition.Values;
        public IEnumerable<BuildingInstance> BuildingInstances => buildingInstancesById.Values;
        public IEnumerable<Vector2Int> DevelopedCells => developedCells;
        public IEnumerable<Vector2Int> RevealedCells => revealedCells;

        public event Action<GridCellData> CellChanged;
        public event Action<BuildingInstance> BuildingPlaced;
        public event Action<BuildingInstance> BuildingRemoved;
        public event Action<IReadOnlyList<Vector2Int>> DevelopmentChanged;
        public event Action<IReadOnlyList<Vector2Int>> RevealChanged;
        public event Action<IReadOnlyList<Vector2Int>> DecorationsCleared;

        public GridMapData(GridMapJson json)
        {
            ChunkSize = Mathf.Max(1, json.chunkSize);
            CameraBounds = json.cameraBounds;

            foreach (GridCellData cell in json.cells)
            {
                Vector2Int position = new Vector2Int(cell.x, cell.y);
                cellsByPosition[position] = cell;
                authoredCellPositions.Add(position);
            }
        }

        public GridCellData GetCell(int x, int y)
        {
            if (cellsByPosition.TryGetValue(new Vector2Int(x, y), out GridCellData cell))
            {
                return cell;
            }

            bool isWater = worldSettings != null && worldSettings.ShouldGenerateWater(x, y);
            bool isWaterGrassBuffer = worldSettings != null && worldSettings.IsInsideWaterGrassBuffer(x, y);
            bool isRoad = !isWater && !isWaterGrassBuffer && IsProceduralRoad(x, y);
            cell = new GridCellData
            {
                x = x,
                y = y,
                type = isRoad ? "road" : isWater ? "water" : "empty",
                owned = false,
                buildingId = null,
                buildingInstanceId = null
            };

            cellsByPosition[new Vector2Int(x, y)] = cell;
            return cell;
        }

        public void SetOwned(int x, int y, bool owned)
        {
            GridCellData cell = GetCell(x, y);
            cell.owned = owned;
            CellChanged?.Invoke(cell);
        }

        public bool PurchaseLand(GridCellData cell)
        {
            if (!CanPurchaseLand(cell))
            {
                return false;
            }

            cell.owned = true;
            CellChanged?.Invoke(cell);
            ClearDecorationsAround(cell.x, cell.y, worldSettings == null ? 0 : worldSettings.decorationClearRadius);
            RevealAround(cell.x, cell.y);
            DevelopAround(cell.x, cell.y, worldSettings == null ? 0 : worldSettings.roadRevealRadius);
            return true;
        }

        public bool CanPurchaseLand(GridCellData cell)
        {
            if (cell == null || cell.owned || cell.CellType != GridCellType.Empty)
            {
                return false;
            }

            if (worldSettings == null)
            {
                return true;
            }

            if (!IsRevealed(cell.x, cell.y))
            {
                return false;
            }

            if (!worldSettings.requireAdjacentOwnedLand || worldSettings.IsInsideStartArea(cell.x, cell.y))
            {
                return true;
            }

            return IsOwnedOrStartArea(cell.x, cell.y + 1)
                || IsOwnedOrStartArea(cell.x + 1, cell.y)
                || IsOwnedOrStartArea(cell.x, cell.y - 1)
                || IsOwnedOrStartArea(cell.x - 1, cell.y);
        }

        public void SetBuilding(int x, int y, string buildingId)
        {
            GridCellData cell = GetCell(x, y);
            cell.buildingId = buildingId;
            CellChanged?.Invoke(cell);
        }

        public bool CanPlaceBuilding(BuildingDefinition definition, GridCellData originCell)
        {
            if (definition == null || originCell == null)
            {
                return false;
            }

            int width = Mathf.Max(1, definition.footprintWidth);
            int height = Mathf.Max(1, definition.footprintHeight);
            if (definition.IsRoad && (width != 1 || height != 1))
            {
                return false;
            }

            for (int y = 0; y < height; y++)
            {
                for (int x = 0; x < width; x++)
                {
                    GridCellData cell = GetCell(originCell.x + x, originCell.y + y);
                    if (cell == null
                        || !cell.owned
                        || cell.CellType == GridCellType.Water
                        || IsRoad(cell.x, cell.y)
                        || !string.IsNullOrEmpty(cell.buildingInstanceId))
                    {
                        return false;
                    }
                }
            }

            return true;
        }

        public BuildingInstance PlaceBuildingInstance(
            BuildingDefinition definition,
            GridCellData originCell,
            BuildingQualityRoll qualityRoll)
        {
            if (!CanPlaceBuilding(definition, originCell))
            {
                return null;
            }

            int width = Mathf.Max(1, definition.footprintWidth);
            int height = Mathf.Max(1, definition.footprintHeight);
            List<Vector2Int> occupiedCells = new List<Vector2Int>(width * height);
            string instanceId = $"building_{nextBuildingInstanceId++}";

            for (int y = 0; y < height; y++)
            {
                for (int x = 0; x < width; x++)
                {
                    GridCellData cell = GetCell(originCell.x + x, originCell.y + y);
                    cell.buildingId = definition.buildingId;
                    cell.buildingInstanceId = instanceId;
                    occupiedCells.Add(new Vector2Int(cell.x, cell.y));
                }
            }

            BuildingInstance instance = new BuildingInstance(
                instanceId,
                definition,
                new Vector2Int(originCell.x, originCell.y),
                occupiedCells,
                qualityRoll.Quality,
                qualityRoll.ProductionMultiplier,
                qualityRoll.ValueMultiplier,
                qualityRoll.Probability,
                definition.ChooseRandomSpritePath());
            buildingInstancesById[instanceId] = instance;
            for (int i = 0; i < occupiedCells.Count; i++)
            {
                clearedDecorationCells.Add(occupiedCells[i]);
            }
            BuildingPlaced?.Invoke(instance);

            for (int i = 0; i < occupiedCells.Count; i++)
            {
                GridCellData cell = GetCell(occupiedCells[i].x, occupiedCells[i].y);
                CellChanged?.Invoke(cell);
            }

            if (definition.IsRoad)
            {
                NotifyRoadNeighbors(originCell.x, originCell.y);
            }

            return instance;
        }

        public bool TryGetBuildingInstance(string instanceId, out BuildingInstance instance)
        {
            if (string.IsNullOrEmpty(instanceId))
            {
                instance = null;
                return false;
            }

            return buildingInstancesById.TryGetValue(instanceId, out instance);
        }

        public bool TryGetBuildingInstanceAtCell(GridCellData cell, out BuildingInstance instance)
        {
            if (cell == null)
            {
                instance = null;
                return false;
            }

            return TryGetBuildingInstance(cell.buildingInstanceId, out instance);
        }

        public void RemoveBuildingInstance(string instanceId)
        {
            if (!TryGetBuildingInstance(instanceId, out BuildingInstance instance))
            {
                return;
            }

            buildingInstancesById.Remove(instanceId);
            bool wasPlayerRoad = instance.Definition != null && instance.Definition.IsRoad;
            BuildingRemoved?.Invoke(instance);
            IReadOnlyList<Vector2Int> occupiedCells = instance.OccupiedCells;
            for (int i = 0; i < occupiedCells.Count; i++)
            {
                GridCellData cell = GetCell(occupiedCells[i].x, occupiedCells[i].y);
                cell.buildingId = null;
                cell.buildingInstanceId = null;
                CellChanged?.Invoke(cell);
            }

            if (wasPlayerRoad)
            {
                NotifyRoadNeighbors(instance.OriginCell.x, instance.OriginCell.y);
            }
        }

        public bool CanRemoveRoad(GridCellData cell)
        {
            return cell != null && GetRoadSource(cell.x, cell.y) != RoadSource.None;
        }

        public bool RemoveRoad(GridCellData cell)
        {
            if (!CanRemoveRoad(cell))
            {
                return false;
            }

            RoadSource source = GetRoadSource(cell.x, cell.y);
            if (source == RoadSource.PlayerBuilt)
            {
                string instanceId = cell.buildingInstanceId;
                RemoveBuildingInstance(instanceId);
                return true;
            }

            Vector2Int position = new Vector2Int(cell.x, cell.y);
            removedAutoRoads.Add(position);
            ClearDecorationsAround(cell.x, cell.y, 0);
            cell.type = "empty";
            cell.buildingId = null;
            cell.buildingInstanceId = null;
            CellChanged?.Invoke(cell);
            NotifyRoadNeighbors(cell.x, cell.y);
            return true;
        }

        // Compatibility wrappers for existing scene bindings and callers.
        public bool CanRemovePlayerRoad(GridCellData cell)
        {
            return CanRemoveRoad(cell);
        }

        public bool RemovePlayerRoad(GridCellData cell)
        {
            return RemoveRoad(cell);
        }

        public void SetProceduralRoadNetwork(ProceduralRoadNetwork roadNetwork)
        {
            proceduralRoadNetwork = roadNetwork;
        }

        public void ConfigureWorld(WorldGenerationSettings settings)
        {
            worldSettings = settings;
        }

        public bool IsDeveloped(int x, int y)
        {
            return worldSettings == null
                || worldSettings.IsInsideStartArea(x, y)
                || developedCells.Contains(new Vector2Int(x, y));
        }

        public bool IsRoadVisible(int x, int y)
        {
            if (GetRoadSource(x, y) == RoadSource.PlayerBuilt)
            {
                return true;
            }

            return IsRoad(x, y) && IsDeveloped(x, y) && IsRevealed(x, y);
        }

        public bool IsRevealed(int x, int y)
        {
            if (cellsByPosition.TryGetValue(new Vector2Int(x, y), out GridCellData cell) && cell.owned)
            {
                return true;
            }

            return worldSettings == null
                || worldSettings.RevealAllForDebug
                || worldSettings.IsInitiallyRevealed(x, y)
                || revealedCells.Contains(new Vector2Int(x, y));
        }

        public void CopyRuntimeRevealedCells(List<Vector2Int> destination)
        {
            if (destination == null)
            {
                return;
            }

            destination.Clear();
            destination.AddRange(revealedCells);
        }

        public void RestoreRuntimeRevealedCells(IEnumerable<Vector2Int> positions)
        {
            revealedCells.Clear();
            if (positions != null)
            {
                foreach (Vector2Int position in positions)
                {
                    revealedCells.Add(position);
                }
            }
            RevealChanged?.Invoke(new List<Vector2Int>(revealedCells));
        }

        public List<MapBuildingSaveState> CaptureBuildingSaveState()
        {
            List<MapBuildingSaveState> states = new List<MapBuildingSaveState>(buildingInstancesById.Count);
            foreach (BuildingInstance instance in buildingInstancesById.Values)
            {
                if (instance?.Definition == null)
                {
                    continue;
                }

                states.Add(new MapBuildingSaveState
                {
                    buildingId = instance.Definition.buildingId,
                    x = instance.OriginCell.x,
                    y = instance.OriginCell.y,
                    quality = (int)instance.Quality,
                    productionMultiplier = instance.ProductionMultiplier,
                    valueMultiplier = instance.ValueMultiplier,
                    qualityProbability = instance.QualityProbability
                });
            }
            return states;
        }

        public List<MapCellSaveState> CaptureOwnedCellSaveState()
        {
            List<MapCellSaveState> states = new List<MapCellSaveState>();
            foreach (GridCellData cell in cellsByPosition.Values)
            {
                if (cell.owned)
                {
                    states.Add(new MapCellSaveState { x = cell.x, y = cell.y });
                }
            }
            return states;
        }

        public void RestoreRuntimeState(
            IEnumerable<MapCellSaveState> ownedCells,
            IEnumerable<MapBuildingSaveState> buildings,
            ChunkedGridMapRenderer renderer)
        {
            if (ownedCells != null)
            {
                foreach (MapCellSaveState state in ownedCells)
                {
                    if (state != null)
                    {
                        SetOwned(state.x, state.y, true);
                    }
                }
            }

            if (buildings == null || renderer == null)
            {
                return;
            }

            foreach (MapBuildingSaveState state in buildings)
            {
                if (state == null || !renderer.TryGetBuildingDefinition(state.buildingId, out BuildingDefinition definition))
                {
                    continue;
                }

                BuildingQualityRoll roll = new BuildingQualityRoll(
                    (BuildingQuality)state.quality,
                    state.productionMultiplier,
                    state.valueMultiplier,
                    state.qualityProbability);
                PlaceBuildingInstance(definition, GetCell(state.x, state.y), roll);
            }
        }

        public bool IsDecorationCleared(int x, int y)
        {
            GridCellData cell = GetCell(x, y);
            return cell.owned
                || !string.IsNullOrEmpty(cell.buildingInstanceId)
                || clearedDecorationCells.Contains(new Vector2Int(x, y));
        }

        public bool TryGetDecorationType(int x, int y, out WorldDecorationType type)
        {
            type = default;
            if (worldSettings == null || worldSettings.IsInsideStartArea(x, y) || IsDecorationCleared(x, y))
            {
                return false;
            }

            GridCellData cell = GetCell(x, y);
            if (cell.CellType == GridCellType.Water || IsRoad(x, y))
            {
                return false;
            }

            float forestNoise = worldSettings.GetForestNoise(x, y);
            float random = worldSettings.GetCellRandom01(x, y, 101);
            if (forestNoise >= 1f - worldSettings.forestDensity)
            {
                if (random <= worldSettings.treeChance)
                {
                    type = forestNoise > 0.72f ? WorldDecorationType.Forest : WorldDecorationType.Tree;
                    return true;
                }
            }

            float cursor = worldSettings.bushChance;
            if (random < cursor)
            {
                type = WorldDecorationType.Bush;
                return true;
            }

            cursor += worldSettings.flowerChance;
            if (random < cursor)
            {
                type = WorldDecorationType.Flower;
                return true;
            }

            cursor += worldSettings.rockChance;
            if (random < cursor)
            {
                type = WorldDecorationType.Rock;
                return true;
            }

            return false;
        }

        public int GetVisualVariant(int x, int y, int variantCount, int salt)
        {
            if (variantCount <= 1 || worldSettings == null)
            {
                return 0;
            }

            return Mathf.Min(variantCount - 1, Mathf.FloorToInt(worldSettings.GetCellRandom01(x, y, salt) * variantCount));
        }

        private void DevelopAround(int centerX, int centerY, int radius)
        {
            if (worldSettings == null)
            {
                return;
            }

            List<Vector2Int> changed = new List<Vector2Int>();
            for (int y = -radius; y <= radius; y++)
            {
                for (int x = -radius; x <= radius; x++)
                {
                    Vector2Int position = new Vector2Int(centerX + x, centerY + y);
                    if (!worldSettings.IsInsideStartArea(position.x, position.y) && developedCells.Add(position))
                    {
                        changed.Add(position);
                    }
                }
            }

            if (changed.Count > 0)
            {
                DevelopmentChanged?.Invoke(changed);
            }
        }

        private void RevealAround(int centerX, int centerY)
        {
            if (worldSettings == null)
            {
                return;
            }

            int radius = Mathf.Max(0, worldSettings.purchaseRevealRadius);
            List<Vector2Int> changed = new List<Vector2Int>();
            for (int y = -radius; y <= radius; y++)
            {
                for (int x = -radius; x <= radius; x++)
                {
                    if (!worldSettings.revealIncludesDiagonals && Mathf.Abs(x) + Mathf.Abs(y) > radius)
                    {
                        continue;
                    }

                    Vector2Int position = new Vector2Int(centerX + x, centerY + y);
                    if (!worldSettings.IsInitiallyRevealed(position.x, position.y) && revealedCells.Add(position))
                    {
                        changed.Add(position);
                    }
                }
            }

            if (changed.Count > 0)
            {
                RevealChanged?.Invoke(changed);
            }
        }

        private bool IsOwnedOrStartArea(int x, int y)
        {
            if (worldSettings.IsInsideStartArea(x, y))
            {
                return true;
            }

            return cellsByPosition.TryGetValue(new Vector2Int(x, y), out GridCellData cell) && cell.owned;
        }

        private void ClearDecorationsAround(int centerX, int centerY, int radius)
        {
            List<Vector2Int> changed = new List<Vector2Int>();
            for (int y = -radius; y <= radius; y++)
            {
                for (int x = -radius; x <= radius; x++)
                {
                    Vector2Int position = new Vector2Int(centerX + x, centerY + y);
                    if (clearedDecorationCells.Add(position))
                    {
                        changed.Add(position);
                    }
                }
            }

            if (changed.Count > 0)
            {
                DecorationsCleared?.Invoke(changed);
            }
        }

        public bool IsRoad(int x, int y)
        {
            if (GetRoadSource(x, y) == RoadSource.PlayerBuilt)
            {
                return true;
            }

            Vector2Int position = new Vector2Int(x, y);
            if (removedAutoRoads.Contains(position))
            {
                return false;
            }

            if (authoredCellPositions.Contains(position)
                && cellsByPosition.TryGetValue(position, out GridCellData authoredCell))
            {
                return authoredCell.CellType == GridCellType.Road;
            }

            if (worldSettings != null
                && (worldSettings.ShouldGenerateWater(x, y)
                    || worldSettings.IsInsideWaterGrassBuffer(x, y)))
            {
                return false;
            }

            return IsProceduralRoad(x, y);
        }

        public RoadSource GetRoadSource(int x, int y)
        {
            Vector2Int position = new Vector2Int(x, y);
            if (cellsByPosition.TryGetValue(position, out GridCellData cell)
                && TryGetBuildingInstanceAtCell(cell, out BuildingInstance instance)
                && instance != null
                && instance.Definition != null
                && instance.Definition.IsRoad)
            {
                return RoadSource.PlayerBuilt;
            }

            if (removedAutoRoads.Contains(position))
            {
                return RoadSource.None;
            }

            if (authoredCellPositions.Contains(position)
                && cellsByPosition.TryGetValue(position, out GridCellData authoredCell))
            {
                return authoredCell.CellType == GridCellType.Road
                    ? RoadSource.AutoGenerated
                    : RoadSource.None;
            }

            if (worldSettings != null
                && (worldSettings.ShouldGenerateWater(x, y)
                    || worldSettings.IsInsideWaterGrassBuffer(x, y)))
            {
                return RoadSource.None;
            }

            return IsProceduralRoad(x, y) ? RoadSource.AutoGenerated : RoadSource.None;
        }

        private void NotifyRoadNeighbors(int x, int y)
        {
            CellChanged?.Invoke(GetCell(x, y + 1));
            CellChanged?.Invoke(GetCell(x + 1, y));
            CellChanged?.Invoke(GetCell(x, y - 1));
            CellChanged?.Invoke(GetCell(x - 1, y));
        }

        private bool IsProceduralRoad(int x, int y)
        {
            return proceduralRoadNetwork != null
                && proceduralRoadNetwork.Enabled
                && proceduralRoadNetwork.IsRoad(x, y);
        }
    }
}
